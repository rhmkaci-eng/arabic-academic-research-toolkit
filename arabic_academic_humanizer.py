# -*- coding: utf-8 -*-
"""
🏛️ مؤنسن ومطهّر الأسلوب الأكاديمي العربي (Arabic Academic Humanizer & Prose Purifier)
المنظومة المنهجية لتطهير النصوص الأكاديمية والعقدية من بصمات الذكاء الاصطناعي ورطانة ChatGPT،
وإعادة صياغتها على سمت أكابر النظار وفق معايير كلية العلوم الإسلامية (خروبة - جامعة الجزائر 1).

المحاور:
1. رصد ومسح كليشيهات وحشو الذكاء الاصطناعي (AI Cliché Blacklist).
2. إزالة مكياج المتكلمين والتزويق الإنشائي والسجع المتكلف.
3. إنفاذ الصرامة الأصولية: التحليل بدلاً من النقد والتفكيك، ونبذ المطلقات.
4. تعريب الرطانة الفلسفية (الجهة الغائية بدلاً من التيليولوجية).
5. حساب مؤشر الأنسنة والرصانة الكلامية (Human Scholarly Index / 100).
"""

import sys
import os
import re
import argparse

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8', errors='ignore')

# 1. كليشيهات وحشو الذكاء الاصطناعي الشائعة (AI Cliché Patterns)
AI_CLICHES = [
    (r'\bمما لا شك فيه\b', 'حشو ذكاء اصطناعي معلب: يُحذف أو يُستبدل بـ «والأصل أن» أو البدء بالقضية رأساً.'),
    (r'\bلا يخفى على أحد\b', 'حشو معلب: يُحذف مباشرة، فالمعلوم لا يُمتنّ به.'),
    (r'\bمن نافلة القول\b', 'حشو لغوي: إن كان نافلة فلماذا يُذكر؟ يُحذف رأساً.'),
    (r'\bيلعب دوراً (محورياً|كبيراً|بارزاً|هاماً|حيوياً|رئيسياً)\b', 'تعبير مترجم ركيك: يُستبدل بـ «يؤثر أثراً بيّناً في» أو «مناطه كذا» أو «أصله كذا».'),
    (r'\bيسلط الضوء على\b', 'استعارة صحفية مكررة: تُستبدل بـ «يُبيّن» أو «يفحص» أو «يُحرر».'),
    (r'\bتسليط الضوء على\b', 'استعارة صحفية مكررة: تُستبدل بـ «بيان» أو «فحص» أو «تحرير».'),
    (r'\bمن الجدير بالذكر\b', 'حشو استهلالي آلي: يُحذف ويبدأ بالمعنى فوراً.'),
    (r'\bجدير بالذكر\b', 'حشو استهلالي آلي: يُحذف ويبدأ بالمعنى فوراً.'),
    (r'\bيجدر بنا الإشارة إلى\b', 'حشو إنشائي: يُحذف ويبدأ بصلب المسألة.'),
    (r'\bحريّ بالبيان\b', 'حشو استهلالي: يُحذف مباشرة.'),
    (r'\bفي هذا السياق المتصل\b|\bفي إطار هذا السياق\b', 'رطانة ربط آلية: يُستعاض عنها بـ «وعليه» أو «وبيان ذلك» أو «ومقتضاه».'),
    (r'\bعلى صعيد آخر\b', 'لغة صحفية: تُستبدل بـ «وبإزاء ذلك» أو «ومقابله».'),
    (r'\bمن زاوية أخرى\b', 'تعبير صحفي: يُستبدل بـ «ومن وجهٍ آخر» أو «واعتباره من جهة كذا».'),
    (r'\bتجدر الإشارة\b', 'حشو آلي: يُحذف رأساً.'),
    (r'\bتجدر بنا الإشارة\b', 'حشو آلي: يُحذف رأساً.'),
    (r'\bوفي ختام هذا (المبحث|المطلب|الفصل)\b', 'استباق وتلخيص روتيني: يُستعاض عنه بحكم جامع مانع لما تم إثباته برهانياً.'),
    (r'\bتعتبر هذه القضية من أهم القضايا\b', 'تعميم فارغ من الماهية: يُستبدل ببيان ماهية القضية ومحل النزاع فيها رأساً.'),
    (r'\bيشكل هذا علامة فارقة\b', 'تهويل إنشائي: يُستبدل بتقرير الأثر العيني المحقق.')
]

# 2. حظر النقد والتفكيك والمحاكمة والسجال (Prohibited Methodological Terms)
METHODOLOGY_VIOLATIONS = [
    (r'(?<!نقد العقل المحض)(?<!نقد ملكة الحكم)(?<!نقد العقل العملي)(?<!نقد الدين )(?<!نقد الشكوكية )\b(نقد|النقد|ننقده|نقده)\b', 
     'حظر بات لمصطلح النقد: يُستبدل بـ «التحليل» أو «الفحص التحليلي» صوناً للموضوعية وتجريداً للخطاب.'),
    (r'\b(تفكيك|التفكيك|نفكك|تفكيكية)\b(?!\s*ما بعد الحداثة)', 
     'حظر بات للتفكيك: إحالة عدمية ما بعد حداثية؛ يُستبدل بـ «التحليل» أو «البيان» أو «إبطال الاستدلال».'),
    (r'\b(محاكمة الخصوم|محاكمة|المحاكمة)\b', 
     'نبرة قضائية مستهجنة: يُستبدل بـ «الفحص والنظر في مقالة كذا».'),
    (r'(?<!تهافت الفلاسفة)(?<!تهافت التهافت)\b(تهافت|التهافت)\b', 
     'لفظ سجالي: يُستبدل بـ «مأزق استدلالي» أو «اضطراب في الدليل».'),
    (r'\b(سجال|سجالية|المقارعة الكلامية)\b', 
     'يُستبدل بـ «المناظرة البرهانية» أو «النظر والمساءلة الإبستمولوجية».')
]

# 3. الرطانة المعربة والمصطلحات المستغربة (Unnatural Loanwords)
TERMINOLOGY_REFINEMENTS = [
    (r'\b(التيليولوجية|التيليولوجي|تيليولوجي)\b', 'رطانة مستغربة: يُستبدل بـ «الجهة الغائية» أو «مبحث الغائية والحكمة والتدبير».'),
    (r'\bمنعطف التنوير\b', 'تعبير أدبي غير مألوف: يُستبدل بـ «عصر التنوير».'),
    (r'\bالأنطولوجي\b|\bالأنطولوجية\b', 'إن كان في معرض برهان إثبات الصانع: يُستبدل بـ «البرهان الوجودي» أو «دليل الوجود العيني».'),
    (r'\bنقل مركز الثقل المعرفي إلى الذات\b', 'صياغة حرفية معربة: يُستعاض عنها بـ «جعل إدراك النفس لذاتها هو الأصل الأولي لابتناء المعارف».')
]

# 4. مكياج المتكلمين والتزويق الإنشائي (Rhetorical Makeup & Fluff)
RHETORICAL_MAKEUP = [
    (r'\b(أحسنتم وأجدتم|بوركت همتكم|نعم النظر والتوجيه)\b', 'مكياج المتكلمين: ثناء متكلف يُحظر استخدامه في المتن والمحاورة.'),
    (r'\b(الرد المفحم|الضربة القاضية|الفارس الهمام)\b', 'تزويق إنشائي رنان: يُستبدل بتقرير النتيجة البرهانية بهدوء ورصانة.'),
    (r'\bقدر الطاقة\b(?=.*(?:من أبرز|من أهم|هو المصنف|هو الكتاب))', 'سوء موضع قدر الطاقة: يُحظر إلصاقه بالظواهر الخارجية، ويُقصر حصراً على عمل الباحث الذاتي.')
]

def analyze_prose(text):
    """تحليل النص ورصد كافة البصمات الآلية والركاكة الأسلوبية"""
    lines = text.split('\n')
    total_words = len(re.findall(r'\w+', text)) or 1
    
    findings = []
    
    # فحص الكليشيهات
    for idx, line in enumerate(lines, 1):
        # 1. AI Clichés
        for pat, note in AI_CLICHES:
            for m in re.finditer(pat, line):
                findings.append({
                    'line': idx,
                    'category': 'بصمة ذكاء اصطناعي (AI Cliché)',
                    'matched': m.group(0),
                    'advice': note,
                    'snippet': line.strip()
                })
        # 2. Methodology Violations
        for pat, note in METHODOLOGY_VIOLATIONS:
            for m in re.finditer(pat, line):
                findings.append({
                    'line': idx,
                    'category': 'مخالفة منهجية (حظر النقد/التفكيك)',
                    'matched': m.group(0),
                    'advice': note,
                    'snippet': line.strip()
                })
        # 3. Terminology Refinements
        for pat, note in TERMINOLOGY_REFINEMENTS:
            for m in re.finditer(pat, line):
                findings.append({
                    'line': idx,
                    'category': 'رطانة فلسفية مستغربة',
                    'matched': m.group(0),
                    'advice': note,
                    'snippet': line.strip()
                })
        # 4. Rhetorical Makeup
        for pat, note in RHETORICAL_MAKEUP:
            for m in re.finditer(pat, line):
                findings.append({
                    'line': idx,
                    'category': 'مكياج إنشائي وتزويق',
                    'matched': m.group(0),
                    'advice': note,
                    'snippet': line.strip()
                })

    # حساب المؤشرات
    penalty = len(findings) * 4
    authenticity_score = max(0, 100 - penalty)
    cliche_density = round((len(findings) / total_words) * 1000, 2)
    
    return {
        'total_words': total_words,
        'findings_count': len(findings),
        'authenticity_score': authenticity_score,
        'cliche_density': cliche_density,
        'findings': findings
    }

def quick_purify_rules(text):
    """تطبيق استبدالات قطعية لتطهير النص من الرطانة المباشرة وفق سمت النظار"""
    t = text
    # تعريب الرطانة الفلسفية مع مراعاة السياق الصرفي
    t = re.sub(r'\bالرؤية التيليولوجية\b', 'الرؤية الغائية', t)
    t = re.sub(r'\bالتيليولوجية\b', 'الجهة الغائية', t)
    t = re.sub(r'\bالتيليولوجي\b', 'الجهد الغائي', t)
    t = re.sub(r'\bتيليولوجي\b', 'غائي', t)
    t = re.sub(r'\bمنعطف التنوير\b', 'عصر التنوير', t)
    
    # حظر التفكيك والنقد والمحاكمة
    t = re.sub(r'\bتفكيك\b', 'تحليل', t)
    t = re.sub(r'\bالتفكيك\b', 'التحليل', t)
    t = re.sub(r'\bتفكيكية\b', 'تحليلية', t)
    t = re.sub(r'(?<!نقد العقل المحض)(?<!نقد ملكة الحكم)(?<!نقد العقل العملي)(?<!نقد الدين )\bنقد\b', 'تحليل', t)
    t = re.sub(r'(?<!نقد العقل المحض)(?<!نقد ملكة الحكم)(?<!نقد العقل العملي)(?<!نقد الدين )\bالنقد\b', 'التحليل', t)
    t = re.sub(r'\bننقده\b', 'نحلله ونفحصه', t)
    t = re.sub(r'\bنقده\b', 'تحليله وفحصه', t)
    t = re.sub(r'\bمحاكمة الخصوم\b', 'فحص مقالات المخالفين', t)
    t = re.sub(r'\bمحاكمة\b', 'فحص ونظر في', t)

    # مسح الحشو والكليشيهات الآلية الفجة
    t = re.sub(r'مما لا شك فيه أن\s*', '', t)
    t = re.sub(r'مما لا شك فيه\s*', '', t)
    t = re.sub(r'لا يخفى على أحد أن\s*', '', t)
    t = re.sub(r'لا يخفى على أحد\s*', '', t)
    t = re.sub(r'من نافلة القول أن\s*', '', t)
    t = re.sub(r'من نافلة القول\s*', '', t)
    t = re.sub(r'من الجدير بالذكر أن\s*', '', t)
    t = re.sub(r'من الجدير بالذكر\s*', '', t)
    t = re.sub(r'جدير بالذكر أن\s*', '', t)
    t = re.sub(r'جدير بالذكر\s*', '', t)
    t = re.sub(r'تجدر الإشارة إلى أن\s*', '', t)
    t = re.sub(r'تجدر الإشارة\s*', '', t)
    t = re.sub(r'يجدر بنا الإشارة إلى أن\s*', '', t)
    t = re.sub(r'يجدر بنا الإشارة\s*', '', t)
    t = re.sub(r'حريّ بالبيان أن\s*', '', t)
    t = re.sub(r'حريّ بالبيان\s*', '', t)

    # الاستعارات الصحفية والمترجمة
    t = re.sub(r'يلعب دوراً (?:محورياً|كبيراً|بارزاً|رئيسياً|هاماً|حيوياً)\s*في\s*', 'يؤثر أثراً بيّناً في ', t)
    t = re.sub(r'يلعب دوراً (?:محورياً|كبيراً|بارزاً|رئيسياً|هاماً|حيوياً)', 'يؤثر أثراً بيّناً', t)
    t = re.sub(r'يسلط الضوء على\s*', 'يُبيّن ', t)
    t = re.sub(r'تسليط الضوء على\s*', 'بيان ', t)
    t = re.sub(r'على صعيد آخر\s*،?', 'وبإزاء ذلك،', t)
    t = re.sub(r'في هذا السياق المتصل\s*،?', 'وعليه،', t)
    t = re.sub(r'في إطار هذا السياق\s*،?', 'ومقتضاه،', t)
    
    # تنظيف الفراغات المزدوجة الناتجة عن الحذف
    t = re.sub(r'[ \t]{2,}', ' ', t)
    return t.strip()

def main():
    parser = argparse.ArgumentParser(description="Arabic Academic Humanizer & Prose Purifier")
    parser.add_argument("file_or_text", help="مسار ملف الماركداون/النص أو نص مباشر بين علامتي تنصيص")
    parser.add_argument("--purify", "-p", action="store_true", help="تطبيق التطهير الآلي المباشر للعبارات وحفظ النص المصحح")
    parser.add_argument("--output", "-o", help="مسار حفظ النص المؤنسن والمطهر")
    args = parser.parse_args()

    content = ""
    is_file = os.path.exists(args.file_or_text)
    if is_file:
        with open(args.file_or_text, 'r', encoding='utf-8') as f:
            content = f.read()
    else:
        content = args.file_or_text

    report = analyze_prose(content)

    print("\n" + "="*65)
    print("🏛️ تقرير مؤنسن ومطهّر الأسلوب الأكاديمي العربي (Arabic Academic Humanizer)")
    print("="*65)
    print(f"📊 إجمالي الكلمات المفحوصة: {report['total_words']}")
    print(f"⚠️ مواضع الركاكة وبصمات الـ AI المرصودة: {report['findings_count']}")
    print(f"📈 كثافة كليشيهات الذكاء الاصطناعي: {report['cliche_density']} كليشيه / 1000 كلمة")
    print(f"💎 مؤشر الرصانة والأصالة البشرية: {report['authenticity_score']} / 100")
    print("="*65)

    if report['findings']:
        print("\n🔍 التفصيل المنهجي للمواضع المرصودة:")
        for idx, f in enumerate(report['findings'][:25], 1):
            print(f" [{idx:02d}] السطر {f['line']} | {f['category']}:")
            print(f"      النص المرصود: «{f['matched']}»")
            print(f"      التوجيه الأكاديمي: {f['advice']}")
            print(f"      السياق: {f['snippet'][:85]}...\n")
        if len(report['findings']) > 25:
            print(f"... وتم طي {len(report['findings']) - 25} موضعاً إضافياً للتركيز.")
    else:
        print("\n✅ النص محكم وصافٍ 100%، خالٍ من بصمات الذكاء الاصطناعي ومكياج المتكلمين.")

    if args.purify or args.output:
        purified = quick_purify_rules(content)
        if args.output:
            with open(args.output, 'w', encoding='utf-8') as f:
                f.write(purified)
            print(f"\n💾 تم حفظ النص المطهر بنجاح في: {args.output}")
        else:
            print("\n📝 معاينة النص المطهر والمؤنسن أولياً:")
            print("-" * 50)
            print(purified[:500] + ("..." if len(purified) > 500 else ""))
            print("-" * 50)

if __name__ == '__main__':
    main()
